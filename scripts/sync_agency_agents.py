#!/usr/bin/env python3
"""Regenerate the agency-* plugins from msitarzewski/agency-agents.

Each division of The Agency (marketing, engineering, ...) becomes one plugin,
plugins/agency-<division>/, holding that division's agent files unchanged,
the upstream MIT license and a generated README. The script also rewrites the
agency-* entries of .claude-plugin/marketplace.json and the agency table in the
root README.md (between the agency:start / agency:end markers).

Usage:
  python3 scripts/sync_agency_agents.py                  # clones upstream
  python3 scripts/sync_agency_agents.py --source DIR     # uses a local clone

Standard library only. Plugin versions follow the upstream commit date
(YYYY.M.D), so each sync that picks up new upstream commits bumps them.
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from datetime import date
from pathlib import Path

UPSTREAM = "https://github.com/msitarzewski/agency-agents"
PREFIX = "agency-"
MARKER = "<!-- Generated by scripts/sync_agency_agents.py: edits are overwritten on the next sync. -->"
README_START = "<!-- agency:start -->"
README_END = "<!-- agency:end -->"

ROOT = Path(__file__).resolve().parent.parent


def git(cwd, *args):
    result = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True)
    return result.stdout.strip() if result.returncode == 0 else ""


def frontmatter(text):
    """Return the frontmatter of an agent file as a dict, or None if it has none.

    Handles the subset upstream uses: `key: value`, quoted values and `|` / `>`
    block scalars. Only used to read name and description for the READMEs; the
    agent files themselves are copied byte for byte.
    """
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    except StopIteration:
        return None
    fields, i = {}, 1
    while i < end:
        match = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", lines[i])
        i += 1
        if not match:
            continue
        key, value = match.group(1), match.group(2).strip()
        if value and value[0] in "|>":
            block = []
            while i < end and (not lines[i].strip() or lines[i].startswith((" ", "\t"))):
                block.append(lines[i].strip())
                i += 1
            value = " ".join(part for part in block if part)
        elif len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
            value = value[1:-1]
        fields[key] = value
    return fields


def collect(source, division):
    """Agent files of one division: markdown with a frontmatter `name`."""
    agents = []
    for path in sorted((source / division).rglob("*.md")):
        meta = frontmatter(path.read_text(encoding="utf-8"))
        if meta and meta.get("name"):
            agents.append((path, meta))
    return agents


def cell(text):
    return re.sub(r"\s+", " ", text).replace("|", "\\|").strip()


def repository_url():
    url = git(ROOT, "remote", "get-url", "origin")
    match = re.search(r"github\.com[:/]([^/]+/[^/]+?)(?:\.git)?/?$", url)
    return f"https://github.com/{match.group(1)}" if match else ""


def plugin_readme(name, label, division, agents, commit, repo_slug):
    rows = "\n".join(
        f"| {cell(meta.get('emoji', ''))} {cell(meta['name'])} | {cell(meta.get('description', ''))} |"
        for _, meta in agents
    )
    return f"""{MARKER}

# {name}

The **{label}** division of [The Agency]({UPSTREAM}): {len(agents)} specialist subagents for Claude Code, copied unchanged from upstream.

## Install

```
/plugin marketplace add {repo_slug}
/plugin install {name}@claude-kit
```

Restart the session afterwards. Plugin agents are namespaced: ask for an agent by name ("use the {agents[0][1]['name']} agent to...") or pick it from `/agents`.

Without the plugin system, copy the files into your Claude Code config:

```bash
cp plugins/{name}/agents/*.md ~/.claude/agents/
```

## Agents

| Agent | What it does |
| --- | --- |
{rows}

## Source and license

Agents from [msitarzewski/agency-agents]({UPSTREAM}/tree/main/{division}) at commit `{commit[:12]}`, MIT license (see [LICENSE](LICENSE)). Regenerate with `python3 scripts/sync_agency_agents.py`.
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, help="local clone of msitarzewski/agency-agents (default: clone it)")
    args = parser.parse_args()

    tmp = None
    if args.source:
        source = args.source.resolve()
    else:
        tmp = tempfile.mkdtemp(prefix="agency-agents-")
        source = Path(tmp) / "agency-agents"
        subprocess.run(["git", "clone", "--depth", "1", UPSTREAM + ".git", str(source)], check=True)

    try:
        divisions = json.loads((source / "divisions.json").read_text(encoding="utf-8"))["divisions"]
        commit = git(source, "rev-parse", "HEAD") or "unknown"
        day = git(source, "log", "-1", "--format=%cs")
        y, m, d = (int(part) for part in (day or date.today().isoformat()).split("-"))
        version = f"{y}.{m}.{d}"
        repo_url = repository_url()
        repo_slug = repo_url.removeprefix("https://github.com/") or "<owner>/claude-kit"
        license_text = (source / "LICENSE").read_text(encoding="utf-8")

        plugins_dir = ROOT / "plugins"
        generated = []
        for division, info in divisions.items():
            agents = collect(source, division)
            if not agents:
                continue
            names = [path.name for path, _ in agents]
            duplicates = sorted({n for n in names if names.count(n) > 1})
            if duplicates:
                sys.exit(f"{division}: several agent files share a name: {', '.join(duplicates)}")

            name = PREFIX + division
            label = info.get("label", division)
            target = plugins_dir / name
            if target.exists():
                shutil.rmtree(target)
            (target / ".claude-plugin").mkdir(parents=True)
            (target / "agents").mkdir()
            for path, _ in agents:
                shutil.copyfile(path, target / "agents" / path.name)
            (target / "LICENSE").write_text(license_text, encoding="utf-8")
            (target / "README.md").write_text(
                plugin_readme(name, label, division, agents, commit, repo_slug), encoding="utf-8"
            )
            description = f"Agents: The Agency's {label} division, {len(agents)} specialist subagents."
            manifest = {
                "name": name,
                "version": version,
                "description": description,
                "author": {"name": "msitarzewski and The Agency contributors", "url": UPSTREAM},
                "homepage": f"{UPSTREAM}/tree/main/{division}",
                **({"repository": repo_url} if repo_url else {}),
                "license": "MIT",
                "keywords": ["agents", "subagents", "the-agency", division],
            }
            (target / ".claude-plugin" / "plugin.json").write_text(
                json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
            )
            generated.append((name, label, len(agents), description))

        # Drop plugins generated earlier for divisions upstream no longer has.
        keep = {name for name, *_ in generated}
        for stale in plugins_dir.glob(PREFIX + "*"):
            readme = stale / "README.md"
            if stale.name not in keep and readme.exists() and readme.read_text(encoding="utf-8").startswith(MARKER):
                shutil.rmtree(stale)

        marketplace_path = ROOT / ".claude-plugin" / "marketplace.json"
        marketplace = json.loads(marketplace_path.read_text(encoding="utf-8"))
        marketplace["plugins"] = [
            p for p in marketplace["plugins"]
            if not (p["name"].startswith(PREFIX) and p.get("source", "").startswith("./plugins/" + PREFIX))
        ] + [
            {
                "name": name,
                "source": f"./plugins/{name}",
                "description": description,
                "version": version,
                "category": "agents",
            }
            for name, _, _, description in generated
        ]
        marketplace_path.write_text(json.dumps(marketplace, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

        readme_path = ROOT / "README.md"
        readme = readme_path.read_text(encoding="utf-8")
        if README_START in readme and README_END in readme:
            table = "\n".join(
                [README_START, "| Plugin | Division | Agents |", "| --- | --- | --- |"]
                + [f"| [{name}](plugins/{name}) | {label} | {count} |" for name, label, count, _ in generated]
                + [README_END]
            )
            readme = re.sub(re.escape(README_START) + r".*?" + re.escape(README_END), lambda _: table, readme, flags=re.S)
            readme_path.write_text(readme, encoding="utf-8")

        total = sum(count for _, _, count, _ in generated)
        print(f"{len(generated)} plugins, {total} agents, version {version}, upstream {commit[:12]}")
    finally:
        if tmp:
            shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    main()
